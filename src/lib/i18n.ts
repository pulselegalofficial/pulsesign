const DICTS: Record<Lang, Dict> = { en, th };

export const dict = (lang: Lang): Dict => DICTS[lang];

/** The "System" actor is stored in the document's language; show it in the reader's. */
export function actorLabel(name: string, lang: Lang): string {
  return name === DICTS.th.system || name === DICTS.en.system ? DICTS[lang].system : name;
}

export function fill(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

export function translator(lang: Lang) {
  const d = DICTS[lang];
  return (key: Key, vars?: Record<string, string | number>) => (vars ? fill(d[key], vars) : d[key]);
}

/** Language from the `lang` cookie, else Accept-Language, else Thai. */
export function detectLang(request: Request): Lang {
  const cookie = request.headers.get('cookie') || '';
  const m = cookie.match(/(?:^|;\s*)lang=(th|en)\b/);
  if (m) return m[1] as Lang;
  const accept = (request.headers.get('accept-language') || '').toLowerCase();
  if (accept && !accept.includes('th') && accept.startsWith('en')) return 'en';
  return 'th';
}
